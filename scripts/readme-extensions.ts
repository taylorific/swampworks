// Regenerates the extension table in the root README.md from every
// `<dir>/manifest.yaml` in the repository, plus each extension's status on
// the swamp registry (published version, deprecation).
//
// The table lives between the EXTENSIONS_START and EXTENSIONS_END markers;
// everything else in the README is left alone.
//
// Usage:
//   deno run --allow-read --allow-write=README.md --allow-net=swamp-club.com \
//     scripts/readme-extensions.ts [--check | --print]
//
// --check exits 1 (and writes nothing) when the README is out of date.
// --print prints the generated table and touches nothing.

import { parse } from "jsr:@std/yaml@1.2.0";

const START =
  "<!-- EXTENSIONS_START: generated by scripts/readme-extensions.ts, do not edit -->";
const END = "<!-- EXTENSIONS_END -->";
const REGISTRY = "https://swamp-club.com";

/** The manifest fields the table uses. */
export interface Manifest {
  name: string;
  version: string;
  description?: string;
  behaviors?: string[];
  /** The legacy spelling of `behaviors`. */
  models?: string[];
  workflows?: string[];
  vaults?: string[];
  datastores?: string[];
  reports?: string[];
  skills?: string[];
}

/** What the registry reports for one extension; null when unpublished. */
export interface RegistryStatus {
  latestVersion: string | null;
  deprecated: boolean;
  supersededBy: string | null;
}

export interface Extension {
  dir: string;
  manifest: Manifest;
  registry: RegistryStatus | null;
}

const CONTENT_KINDS = [
  ["behaviors", "behavior"],
  ["workflows", "workflow"],
  ["vaults", "vault"],
  ["datastores", "datastore"],
  ["reports", "report"],
  ["skills", "skill"],
] as const;

/** "1 behavior, 2 workflows" from the manifest's content lists. */
export function contents(m: Manifest): string {
  const count = (key: (typeof CONTENT_KINDS)[number][0]) =>
    key === "behaviors"
      ? (m.behaviors?.length ?? 0) + (m.models?.length ?? 0)
      : m[key]?.length ?? 0;
  return CONTENT_KINDS
    .map(([key, noun]) => [count(key), noun] as const)
    .filter(([n]) => n > 0)
    .map(([n, noun]) => `${n} ${noun}${n === 1 ? "" : "s"}`)
    .join(", ");
}

/** The first sentence of a description, on one line, safe inside a table. */
export function summary(description: string | undefined): string {
  if (!description) return "";
  const flat = description.replace(/\s+/g, " ").trim();
  const sentence = /^(.+?[.!?])(\s|$)/.exec(flat)?.[1] ?? flat;
  return sentence.replace(/\|/g, "\\|");
}

function registryCell(name: string, r: RegistryStatus | null): string {
  if (!r?.latestVersion) return "not published yet";
  const link = `[\`${r.latestVersion}\`](${REGISTRY}/extensions/${name})`;
  if (!r.deprecated) return link;
  return `${link} — deprecated${
    r.supersededBy ? `, use \`${r.supersededBy}\`` : ""
  }`;
}

/** Renders the markdown table (without markers). */
export function renderTable(extensions: Extension[]): string {
  if (extensions.length === 0) return "_No extensions yet._";
  const rows = extensions.map(({ dir, manifest: m, registry }) =>
    `| [${m.name}](${dir}/) | ${summary(m.description)} | ${
      contents(m)
    } | \`${m.version}\` | ${registryCell(m.name, registry)} |`
  );
  return [
    "| Extension | Description | Contents | Version | Registry |",
    "| --------- | ----------- | -------- | ------- | -------- |",
    ...rows,
  ].join("\n");
}

/** Replaces the text between the markers, or fails if they are missing. */
export function replaceBetweenMarkers(readme: string, body: string): string {
  const start = readme.indexOf(START);
  const end = readme.indexOf(END);
  if (start === -1 || end === -1 || end < start) {
    throw new Error(
      `README.md must contain the markers:\n${START}\n${END}`,
    );
  }
  return `${readme.slice(0, start + START.length)}\n${body}\n${
    readme.slice(end)
  }`;
}

async function fetchRegistry(name: string): Promise<RegistryStatus | null> {
  const res = await fetch(`${REGISTRY}/api/v1/extensions/${name}`, {
    signal: AbortSignal.timeout(15000),
  });
  if (res.status === 404) {
    await res.body?.cancel();
    return null;
  }
  if (!res.ok) {
    throw new Error(`Registry lookup for ${name} failed: HTTP ${res.status}`);
  }
  const data = await res.json() as {
    latestVersion?: string | null;
    deprecatedAt?: string | null;
    supersededBy?: string | null;
  };
  return {
    latestVersion: data.latestVersion ?? null,
    deprecated: !!data.deprecatedAt,
    supersededBy: data.supersededBy ?? null,
  };
}

async function findExtensions(root: string): Promise<Extension[]> {
  const found: Extension[] = [];
  for await (const entry of Deno.readDir(root)) {
    if (!entry.isDirectory || entry.name.startsWith(".")) continue;
    let text: string;
    try {
      text = await Deno.readTextFile(`${root}/${entry.name}/manifest.yaml`);
    } catch (err) {
      if (err instanceof Deno.errors.NotFound) continue;
      throw err;
    }
    const manifest = parse(text) as Manifest;
    if (!manifest?.name || !manifest?.version) {
      throw new Error(`${entry.name}/manifest.yaml has no name or version`);
    }
    found.push({
      dir: entry.name,
      manifest,
      registry: await fetchRegistry(manifest.name),
    });
  }
  return found.sort((a, b) => a.manifest.name.localeCompare(b.manifest.name));
}

if (import.meta.main) {
  const check = Deno.args.includes("--check");
  const root = new URL("..", import.meta.url).pathname.replace(/\/$/, "");
  const table = renderTable(await findExtensions(root));
  if (Deno.args.includes("--print")) {
    console.log(table);
    Deno.exit(0);
  }
  const readmePath = `${root}/README.md`;
  const current = await Deno.readTextFile(readmePath);
  const updated = replaceBetweenMarkers(current, table);
  if (updated === current) {
    console.log("README.md extension table is up to date.");
  } else if (check) {
    console.error(
      "README.md extension table is out of date. Run: deno run --allow-read --allow-write=README.md --allow-net=swamp-club.com scripts/readme-extensions.ts",
    );
    Deno.exit(1);
  } else {
    await Deno.writeTextFile(readmePath, updated);
    console.log("Updated the README.md extension table.");
  }
}
